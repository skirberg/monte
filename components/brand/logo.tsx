import { cn } from "@/lib/cn";
import { SITE_NAME } from "@/lib/seo";
import { ICON_CURVE, LOCKUP, LOCKUP_CURVE, LOCKUP_WORD } from "./logo-art";

/*
  The Monte mark (November 13, 2026; DESIGN.md, "Mark"): a bell curve in clay. Monte means mountain, and the bell is
  the mountain every pile of random grains settles into, the shape the home page board draws. The lockup sets it on
  the baseline of "monte" (Bricolage Grotesque 96pt ExtraBold, outlined), as tall as the t, one stem away.
  The geometry is generated by scripts/make-logo.py into logo-art.ts. The header, footer, tab icon, app icons, share
  cards and cheat sheets all build from the strings below, so there is one source.
*/

/** The mark alone as an SVG string (512 square), for icon generators. A color starting with "." is a class. */
export function markSvg(color: string, head = "") {
  const fill = color.startsWith(".") ? `class="${color.slice(1)}"` : `fill="${color}"`;
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 512 512">${head}<path d="${ICON_CURVE}" ${fill}/></svg>`;
}

/** The full lockup as an SVG string, for share cards and cheat sheets. */
export function lockupSvg(ink: string, clay: string) {
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${LOCKUP.width} ${LOCKUP.height}"><path d="${LOCKUP_CURVE}" fill="${clay}"/><path d="${LOCKUP_WORD}" fill="${ink}"/></svg>`;
}
/** Width over height of the lockup, so callers can size it from a height. */
export const LOCKUP_RATIO = LOCKUP.width / LOCKUP.height;

/**
 * The lockup. Sized by height; 18 px in the header puts the x-height near the 14 px nav text. It never grows wider
 * than its box: on a 320 px phone the 56 px /brand/ logo would be 344 px wide, so it shrinks to fit instead.
 */
export function Wordmark({ className }: { className?: string }) {
  return (
    <svg
      viewBox={`0 0 ${LOCKUP.width} ${LOCKUP.height}`}
      className={cn("h-4.5 w-auto max-w-full shrink-0", className)}
      role="img"
      aria-label={SITE_NAME}
    >
      <path d={LOCKUP_CURVE} fill="var(--clay)" />
      <path d={LOCKUP_WORD} fill="var(--ink)" />
    </svg>
  );
}
