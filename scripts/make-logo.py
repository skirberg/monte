"""Draws the Monte logo and writes components/brand/logo-art.ts (DESIGN.md, "Mark").

The mark is a bell curve: monte means mountain, and the shape every pile of random grains settles into.
The lockup sets it beside "monte" outlined from Bricolage Grotesque (opsz 96, wdth 100, wght 800, the 96pt ExtraBold
cut), kerned with HarfBuzz and tracked -2%. Construction (Figma, "6 · Lockup construction", option B):
  - the curve stands on the word's baseline (its flat tails are the ground the letters stand on);
  - its height is the t's ascender plus 2% overshoot for the round peak;
  - the gap to the m is one stem of the type.
Letters are outlines, not live text, so the logo is identical everywhere and needs no font at runtime.

    python -m venv .venv-logo && .venv-logo/bin/pip install fonttools uharfbuzz
    .venv-logo/bin/python scripts/make-logo.py
"""
import io
import math
import re
import urllib.request
from pathlib import Path

import uharfbuzz as hb
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.ttLib import TTFont

CSS = "https://fonts.googleapis.com/css2?family=Bricolage+Grotesque:opsz,wdth,wght@96,100,800"
OUT = Path(__file__).resolve().parent.parent / "components" / "brand" / "logo-art.ts"
WORD, TRACK = "monte", -0.02

# The curve, in its drawing units: a normal curve (sigma 68) on a 10-unit ground, tails 232 either side of the peak.
SIGMA, PEAK, GROUND, HALF = 68, 236, 10, 232


def curve(scale: float, x0: float, base: float) -> str:
    """Closed path: ground line, the curve, back down. Sampled every 4 units, which is smooth at any size."""
    pts = []
    for i in range(0, 2 * HALF + 1, 4):
        x = i - HALF
        y = GROUND + PEAK * math.exp(-(x * x) / (2 * SIGMA * SIGMA))
        pts.append(f"{x0 + i * scale:.1f} {base - y * scale:.1f}")
    return f"M{x0:.1f} {base:.1f}L" + "L".join(pts) + f"L{x0 + 2 * HALF * scale:.1f} {base:.1f}Z"


def main() -> None:
    css = urllib.request.urlopen(CSS).read().decode()
    url = re.search(r"src: url\((.+?)\) format\('truetype'\)", css).group(1)
    data = urllib.request.urlopen(url).read()
    tt = TTFont(io.BytesIO(data))
    upm = tt["head"].unitsPerEm
    gs, cmap, order = tt.getGlyphSet(), tt.getBestCmap(), tt.getGlyphOrder()

    def bounds(ch: str):
        from fontTools.pens.boundsPen import BoundsPen
        p = BoundsPen(gs)
        gs[cmap[ord(ch)]].draw(p)
        return p.bounds  # xMin, yMin, xMax, yMax

    asc = bounds("t")[3]
    stem = bounds("ı")[2] - bounds("ı")[0]
    lo = min(bounds(c)[1] for c in WORD)  # round letters overshoot below the baseline

    h = asc * 1.02
    scale = h / (GROUND + PEAK)
    cw = 2 * HALF * scale
    base = h  # baseline in SVG units (y grows down); the curve's top sits at 0

    face = hb.Face(data)
    font = hb.Font(face)
    buf = hb.Buffer()
    buf.add_str(WORD)
    buf.guess_segment_properties()
    hb.shape(font, buf, {"kern": True, "liga": False})
    x = cw + stem - bounds("m")[0]
    paths = []
    for i, (info, pos) in enumerate(zip(buf.glyph_infos, buf.glyph_positions)):
        pen = SVGPathPen(gs, ntos=lambda v: f"{v:.1f}".rstrip("0").rstrip("."))
        gs[order[info.codepoint]].draw(TransformPen(pen, (1, 0, 0, -1, x + pos.x_offset, base)))
        paths.append(pen.getCommands())
        last_x = x
        x += pos.x_advance + (TRACK * upm if i < len(WORD) - 1 else 0)
    width = last_x + bounds("e")[2]
    height = base - lo

    # The icon on its own: the same curve centred in a 512 square.
    icon_scale = 464 / (2 * HALF)
    icon_h = (GROUND + PEAK) * icon_scale
    icon = curve(icon_scale, 24, 256 + icon_h / 2)

    OUT.write_text(
        "// Generated by scripts/make-logo.py. Do not edit by hand: change the script and run it again.\n"
        "// The lockup: the clay curve and the word outlined from Bricolage Grotesque 96pt ExtraBold (DESIGN.md, \"Mark\").\n"
        f"export const LOCKUP = {{ width: {width:.1f}, height: {height:.1f} }} as const;\n"
        f"export const LOCKUP_CURVE = \"{curve(scale, 0, base)}\";\n"
        f"export const LOCKUP_WORD = \"{''.join(paths)}\";\n"
        "// The mark alone, centred in a 512 square: favicon, app icons.\n"
        f"export const ICON_CURVE = \"{icon}\";\n"
    )
    print(f"wrote {OUT.name}: lockup {width:.0f} x {height:.0f}, t {asc}, stem {stem}, curve {cw:.0f} x {h:.0f}")


if __name__ == "__main__":
    main()
