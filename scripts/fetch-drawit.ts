// Real series for "What happens next?" on the home page (components/landing/draw-it.tsx).
// Writes lib/play/data/drawit.json from Tickerz's public history files (no key, CORS open):
//   https://tickerz.com/api/indices/<ticker>/history.csv
//
// Only the tickers below are read: an allowlist, so a new Tickerz index never lands on Monte by itself.
// Which part of each series is shown and hidden lives in lib/play/drawit.ts.
//
// Safe as a prebuild step: it never fails the build. A ticker that errors keeps its last saved series,
// and the file is written only when every ticker has a series.

import { readFileSync, writeFileSync, renameSync } from "node:fs";
import { fileURLToPath } from "node:url";

const OUT = fileURLToPath(new URL("../lib/play/data/drawit.json", import.meta.url));
const TIMEOUT = 10000;

/** ticker -> how its rows become points. `daily-to-month` averages each complete month (sea ice). */
type Kind = "month" | "daily-to-month";
type Row = [period: string, value: number];

const TICKERS: Record<string, Kind> = {
  BOOM: "month",
  PPM: "month",
  ICE: "daily-to-month",
  POTHOLE: "month",
};

async function history(ticker: string): Promise<Row[]> {
  const url = `https://tickerz.com/api/indices/${ticker.toLowerCase()}/history.csv`;
  const r = await fetch(url, { headers: { "User-Agent": "monte-build/1.0 (https://monte.markets)" }, signal: AbortSignal.timeout(TIMEOUT) });
  if (!r.ok) throw new Error(`${r.status} ${url}`);
  const [head, ...lines] = (await r.text()).trim().split("\n");
  const cols = head.split(",");
  const iP = cols.indexOf("period");
  const iV = cols.indexOf("value");
  if (iP < 0 || iV < 0) throw new Error(`unexpected columns: ${head}`);
  const rows: Row[] = [];
  for (const line of lines) {
    const c = line.split(",");
    const v = Number(c[iV]);
    if (/^\d{4}-\d{2}-\d{2}$/.test(c[iP]) && Number.isFinite(v)) rows.push([c[iP], v]);
  }
  rows.sort((a, b) => a[0].localeCompare(b[0]));
  return rows;
}

const daysIn = (ym: string) => new Date(Date.UTC(+ym.slice(0, 4), +ym.slice(5, 7), 0)).getUTCDate();

/** Calendar-month means, in millions, keeping only months with nearly every day (the current month is left out). */
export function monthlyMeans(rows: Row[]): Row[] {
  const by = new Map<string, number[]>();
  for (const [p, v] of rows) {
    const k = p.slice(0, 7);
    if (!by.has(k)) by.set(k, []);
    by.get(k)!.push(v);
  }
  const out: Row[] = [];
  for (const [k, vs] of by) if (vs.length >= daysIn(k) - 2) out.push([k, Math.round((vs.reduce((a, b) => a + b, 0) / vs.length / 1e6) * 100) / 100]);
  return out;
}

function points(kind: Kind, rows: Row[]): Row[] {
  if (kind === "daily-to-month") return monthlyMeans(rows);
  if (kind === "month") return rows.map(([p, v]) => [p.slice(0, 7), v]);
  return rows;
}

type Saved = { series?: Record<string, { cadence: string; points: Row[] }> };

function readOld(): Saved | null {
  try {
    return JSON.parse(readFileSync(OUT, "utf8"));
  } catch {
    return null;
  }
}

async function main() {
  const old = readOld();
  const series: NonNullable<Saved["series"]> = {};
  let fresh = 0;
  for (const [t, kind] of Object.entries(TICKERS)) {
    try {
      const pts = points(kind, await history(t));
      if (pts.length < 30) throw new Error(`only ${pts.length} points`);
      series[t] = { cadence: "month", points: pts };
      fresh++;
    } catch (e) {
      console.warn(`fetch-drawit: ${t} failed (${e instanceof Error ? e.message : e}), keeping the last saved series`);
      if (old?.series?.[t]) series[t] = old.series[t];
    }
  }
  if (Object.keys(series).length < Object.keys(TICKERS).length) {
    console.warn("fetch-drawit: a ticker has no series at all, file left as it was");
    return;
  }
  const same = JSON.stringify(series) === JSON.stringify(old?.series);
  if (same) {
    console.log("fetch-drawit: no new numbers, file left as it was");
    return;
  }
  const out = { note: "Generated by scripts/fetch-drawit.ts from Tickerz's public history files. ICE is a monthly mean in millions of square kilometres.", made: new Date().toISOString(), series };
  const tmp = `${OUT}.tmp`;
  writeFileSync(tmp, JSON.stringify(out) + "\n");
  renameSync(tmp, OUT);
  console.log(`fetch-drawit: wrote ${fresh} of ${Object.keys(TICKERS).length} fresh series`);
}

// Never hold up a build.
setTimeout(() => {
  console.warn("fetch-drawit: timed out, file left as it was");
  process.exit(0);
}, 30000).unref();

main()
  .catch((e: unknown) => console.warn(`fetch-drawit: skipped (${e instanceof Error ? e.message : e})`))
  .finally(() => process.exit(0));
